// Extracts the content + widget code from the original single-file HTML build
// so we never hand-retype 1300+ lines of lesson data (which guarantees fidelity).
//
//   PHASES + DIAGRAMS  -> src/data/content.js   (ES module, imported by React)
//   widget functions   -> public/legacy-widgets.js (classic script; its top-level
//                         function declarations become window globals, which the
//                         inline oninput/onclick handlers in concept bodies use)
//
// Run with: npm run extract
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const projectRoot = resolve(__dirname, '..')
const SOURCE = resolve(projectRoot, '..', 'ai_engineer_learning_hub_2.html')

const html = readFileSync(SOURCE, 'utf8')

function idx(marker) {
  const i = html.indexOf(marker)
  if (i === -1) throw new Error(`Marker not found in source HTML: ${marker}`)
  return i
}

const MK_PHASES = 'const PHASES = ['
const CMT_DIAGRAMS = '/* ============================= DIAGRAMS'
const MK_DIAGRAMS = 'const DIAGRAMS = {'
const CMT_WIDGETS = '/* ============================= WIDGETS'
const CMT_STATE = '/* ============================= STATE'

const phasesText = html.slice(idx(MK_PHASES), idx(CMT_DIAGRAMS)).trim()
const diagramsText = html.slice(idx(MK_DIAGRAMS), idx(CMT_WIDGETS)).trim()
const widgetsText = html.slice(idx(CMT_WIDGETS), idx(CMT_STATE)).trim()

const banner = '// AUTO-GENERATED by scripts/extract-content.mjs — DO NOT EDIT BY HAND.\n'

const contentModule =
  banner +
  '// Source: ../ai_engineer_learning_hub_2.html (PHASES + DIAGRAMS, verbatim).\n\n' +
  'export ' + phasesText + '\n\n' +
  'export ' + diagramsText + '\n'

const legacyScript =
  banner +
  '// Classic (non-module) script: top-level function declarations register on\n' +
  '// window so inline oninput/onclick handlers in concept bodies resolve them.\n\n' +
  widgetsText + '\n\n' +
  '// const declarations do not auto-attach to window, so expose the registry:\n' +
  'window.WIDGET_INIT = WIDGET_INIT;\n'

mkdirSync(resolve(projectRoot, 'src', 'data'), { recursive: true })
mkdirSync(resolve(projectRoot, 'public'), { recursive: true })
writeFileSync(resolve(projectRoot, 'src', 'data', 'content.js'), contentModule)
writeFileSync(resolve(projectRoot, 'public', 'legacy-widgets.js'), legacyScript)

const countPhases = (phasesText.match(/id:'p\d+', num:/g) || []).length
const countConcepts = (phasesText.match(/, title:'/g) || []).length
console.log(`Extracted: ${countPhases} phases, ~${countConcepts} concepts`)
console.log('Wrote src/data/content.js and public/legacy-widgets.js')
